package app

import (
	"context"
	"errors"
	"os"
	"os/user"
	"strings"
	"time"

	"github.com/dbfactory-io/pgcellar/internal/barman"
	"github.com/dbfactory-io/pgcellar/internal/sshkeys"
)

// sshTestTimeout bounds one SSH connection test (ssh itself gives up after
// ConnectTimeout=10).
const sshTestTimeout = 30 * time.Second

// SSHKeyView is what the SSH key page shows. It holds the public key only.
type SSHKeyView struct {
	PublicKey string `json:"public_key"`
	Host      string `json:"host"`    // how PostgreSQL reaches pgCellar (ssh_host)
	Port      int    `json:"port"`    // port of the SSH companion container (ssh_port)
	Created   bool   `json:"created"` // the pair was generated by this call
}

// SSHHost is the name PostgreSQL servers use to reach this host over SSH:
// ssh_host of pgcellar.yaml, or the host name of this machine (the container
// name in Docker).
func (a *App) SSHHost() string {
	if h := strings.TrimSpace(a.Config().SSHHost); h != "" {
		return h
	}
	h, _ := os.Hostname()
	return h
}

// DefaultSSHPort is the port of the SSH companion container.
const DefaultSSHPort = 2222

// SSHPort is the port of the SSH companion container: ssh_port of
// pgcellar.yaml, 2222 when it is not set.
func (a *App) SSHPort() int {
	if p := a.Config().SSHPort; p > 0 {
		return p
	}
	return DefaultSSHPort
}

// sshHome is the home directory whose ~/.ssh holds the key: the Barman user's
// when pgCellar can look it up, otherwise the current user's.
func (a *App) sshHome() string {
	if a.SSHHome != "" {
		return a.SSHHome
	}
	if name := a.Config().Barman.User; name != "" {
		if u, err := user.Lookup(name); err == nil && u.HomeDir != "" {
			return u.HomeDir
		}
	}
	h, _ := os.UserHomeDir()
	return h
}

// SSHKey returns the public key, creating the pair the first time (the
// creation is written to the audit log). The private key is never returned.
func (a *App) SSHKey(actor string) (SSHKeyView, error) {
	home := a.sshHome()
	created, err := sshkeys.Ensure(home)
	if err != nil {
		return SSHKeyView{}, err
	}
	if created {
		_ = a.Store.AddAudit(actor, "sshkey.create", "", "ed25519 key pair created in "+sshkeys.Dir(home))
	}
	pub, err := sshkeys.PublicKey(home)
	if err != nil {
		return SSHKeyView{}, err
	}
	return SSHKeyView{PublicKey: pub, Host: a.SSHHost(), Port: a.SSHPort(), Created: created}, nil
}

// TestSSH runs the SSH connection test of one server (its ssh_command) through
// the audited runner. A refusal is an error; a failed connection is a result.
func (a *App) TestSSH(ctx context.Context, actor, name string) (sshkeys.TestResult, error) {
	if !barman.ValidName(name) {
		return sshkeys.TestResult{}, ErrNotFound
	}
	files, err := barman.LoadServers(a.barmanConfigDir())
	if err != nil {
		return sshkeys.TestResult{}, err
	}
	f := findFile(files, name)
	if f == nil {
		return sshkeys.TestResult{}, ErrNotFound
	}
	if strings.TrimSpace(f.SSHCommand) == "" {
		return sshkeys.TestResult{}, &ConflictError{Msg: "This server has no ssh_command to test."}
	}
	if a.Tools == nil {
		return sshkeys.TestResult{}, errors.New("no command runner")
	}
	if _, err := a.SSHKey(actor); err != nil {
		return sshkeys.TestResult{}, err
	}
	ctx, cancel := context.WithTimeout(barman.WithTarget(barman.WithActor(ctx, actor), name), sshTestTimeout)
	defer cancel()
	return sshkeys.TestConnection(ctx, a.Tools, f.SSHCommand), nil
}

// AuthorizedKeys lists the keys allowed to push WAL files, read from the file
// every time.
func (a *App) AuthorizedKeys() ([]sshkeys.AuthorizedKey, error) {
	keys, err := sshkeys.ListAuthorized(a.sshHome())
	if keys == nil {
		keys = []sshkeys.AuthorizedKey{}
	}
	return keys, err
}

// AllowSSHKey authorises the key of the postgres user of a PostgreSQL server
// to push WAL files of that Barman server, and nothing else. The public key is
// pasted by a person; it is checked here.
func (a *App) AllowSSHKey(actor, server, publicKey string) (sshkeys.AuthorizedKey, error) {
	if !barman.ValidName(server) {
		return sshkeys.AuthorizedKey{}, ErrNotFound
	}
	files, err := barman.LoadServers(a.barmanConfigDir())
	if err != nil {
		return sshkeys.AuthorizedKey{}, err
	}
	if findFile(files, server) == nil {
		return sshkeys.AuthorizedKey{}, ErrNotFound
	}
	if _, _, perr := sshkeys.ParsePublicKey(publicKey); perr != nil {
		return sshkeys.AuthorizedKey{}, &ProblemsError{Problems: []string{perr.Error()}}
	}
	home := a.sshHome()
	fp, err := sshkeys.Allow(home, server, publicKey)
	if errors.Is(err, sshkeys.ErrDuplicate) {
		return sshkeys.AuthorizedKey{}, &ConflictError{Msg: "This key is already authorised."}
	}
	if err != nil {
		return sshkeys.AuthorizedKey{}, err
	}
	_ = a.Store.AddAudit(actor, "sshkey.allow", server, "key "+fp+" may run \""+sshkeys.ForcedCommand(server)+"\" only")
	keys, err := sshkeys.ListAuthorized(home)
	if err != nil {
		return sshkeys.AuthorizedKey{}, err
	}
	for _, k := range keys {
		if k.Fingerprint == fp {
			return k, nil
		}
	}
	return sshkeys.AuthorizedKey{Server: server, Fingerprint: fp}, nil
}

// RevokeSSHKey removes the key with this fingerprint from the file.
func (a *App) RevokeSSHKey(actor, fingerprint string) error {
	k, err := sshkeys.Revoke(a.sshHome(), strings.TrimSpace(fingerprint))
	if errors.Is(err, sshkeys.ErrNoSuchKey) {
		return ErrNotFound
	}
	if err != nil {
		return err
	}
	_ = a.Store.AddAudit(actor, "sshkey.revoke", k.Server, "key "+k.Fingerprint+" removed")
	return nil
}
