// Vault configures the off-site copy: after each backup, and every
// WALInterval for the WAL files, pgCellar copies the Barman directory of each
// server to an S3 bucket with restic (one restic repository per server,
// encrypted on this host before it leaves). Keys that have a default are
// pointers: nil = absent = the default, so Save never writes a default.
//
// No secret lives here: the S3 secret key is read from SecretKeyFile, and the
// restic password is generated by pgCellar into PasswordFile.
type Vault struct {
	// Enabled turns the off-site copy on. Absent = false.
	Enabled bool `yaml:"enabled,omitempty" json:"enabled"`
	// Endpoint is the S3 endpoint, with its scheme:
	// https://s3.gra.io.cloud.ovh.net for OVHcloud in Gravelines.
	Endpoint string `yaml:"endpoint,omitempty" json:"endpoint"`
	// Region is the S3 region ("gra"). Absent = us-east-1, what most
	// S3-compatible services accept when they have only one.
	Region string `yaml:"region,omitempty" json:"region"`
	// Bucket is the bucket name. It must exist: pgCellar never creates it.
	Bucket string `yaml:"bucket,omitempty" json:"bucket"`
	// Prefix is the folder inside the bucket, so that several pgCellar
	// instances can share one bucket. Absent = "pgcellar".
	Prefix *string `yaml:"prefix,omitempty" json:"prefix"`
	// AccessKey is the S3 access key id (not a secret on its own).
	AccessKey string `yaml:"access_key,omitempty" json:"access_key"`
	// SecretKeyFile holds the S3 secret key, nothing else (0600, owned by the
	// user pgCellar runs as). Absent = <data_dir>/vault/s3-secret-key.
	SecretKeyFile string `yaml:"secret_key_file,omitempty" json:"secret_key_file"`
	// PasswordFile holds the restic password that encrypts every copy.
	// pgCellar writes it the first time it needs it. Absent =
	// <data_dir>/vault/restic-password.
	PasswordFile string `yaml:"password_file,omitempty" json:"password_file"`
	// Quota is the size of the storage bought, "500GB" or "2TB". pgCellar
	// warns at 80 % and 100 %, and never stops a copy because of it. Absent =
	// no quota.
	Quota string `yaml:"quota,omitempty" json:"quota"`
	// WALInterval is how often the WAL files received since the last copy are
	// sent. 0 = only after a backup. Absent = 15m.
	WALInterval *time.Duration `yaml:"wal_interval,omitempty" json:"wal_interval"`
	// Keep is how many restic snapshots are kept (restic forget --prune).
	Keep VaultKeep `yaml:"keep,omitempty" json:"keep"`
	// MaxAge: a server whose last good copy is older than this turns orange.
	// Absent = 36h.
	MaxAge *time.Duration `yaml:"max_age,omitempty" json:"max_age"`
}

// VaultKeep is the retention of the restic snapshots of one server. Absent
// keys take the default; a key set to 0 keeps nothing of that kind.
type VaultKeep struct {
	Last    *int `yaml:"last,omitempty" json:"last"`
	Daily   *int `yaml:"daily,omitempty" json:"daily"`
	Weekly  *int `yaml:"weekly,omitempty" json:"weekly"`
	Monthly *int `yaml:"monthly,omitempty" json:"monthly"`
}

// Defaults of the vault block.
const (
	DefaultVaultRegion      = "us-east-1"
	DefaultVaultPrefix      = "pgcellar"
	DefaultVaultWALInterval = 15 * time.Minute
	MinVaultWALInterval     = time.Minute
	DefaultVaultMaxAge      = 36 * time.Hour
	DefaultVaultKeepDaily   = 7
	DefaultVaultKeepWeekly  = 4
)

// EffectiveRegion resolves vault.region.
func (v Vault) EffectiveRegion() string {
	if r := strings.TrimSpace(v.Region); r != "" {
		return r
	}
	return DefaultVaultRegion
}

// EffectivePrefix resolves vault.prefix, without a leading or trailing slash.
func (v Vault) EffectivePrefix() string {
	if v.Prefix == nil {
		return DefaultVaultPrefix
	}
	return strings.Trim(strings.TrimSpace(*v.Prefix), "/")
}

// EffectiveWALInterval resolves vault.wal_interval (0 = after backups only).
func (v Vault) EffectiveWALInterval() time.Duration {
	if v.WALInterval == nil {
		return DefaultVaultWALInterval
	}
	return *v.WALInterval
}

// EffectiveMaxAge resolves vault.max_age.
func (v Vault) EffectiveMaxAge() time.Duration {
	if v.MaxAge == nil {
		return DefaultVaultMaxAge
	}
	return *v.MaxAge
}

// EffectiveSecretKeyFile resolves vault.secret_key_file.
func (v Vault) EffectiveSecretKeyFile(dataDir string) string {
	if f := strings.TrimSpace(v.SecretKeyFile); f != "" {
		return f
	}
	return filepath.Join(dataDir, "vault", "s3-secret-key")
}

// EffectivePasswordFile resolves vault.password_file.
func (v Vault) EffectivePasswordFile(dataDir string) string {
	if f := strings.TrimSpace(v.PasswordFile); f != "" {
		return f
	}
	return filepath.Join(dataDir, "vault", "restic-password")
}

// QuotaBytes is vault.quota in bytes, 0 when there is none (or it does not
// parse, which validation reports).
func (v Vault) QuotaBytes() int64 {
	n, err := ParseSize(v.Quota)
	if err != nil {
		return 0
	}
	return n
}

func keepOr(p *int, def int) int {
	if p == nil {
		return def
	}
	return *p
}

// Resolved returns last, daily, weekly and monthly with the defaults applied.
func (k VaultKeep) Resolved() (last, daily, weekly, monthly int) {
	return keepOr(k.Last, 0), keepOr(k.Daily, DefaultVaultKeepDaily), keepOr(k.Weekly, DefaultVaultKeepWeekly), keepOr(k.Monthly, 0)
}

// Args are the --keep-* options of restic forget.
func (k VaultKeep) Args() []string {
	last, daily, weekly, monthly := k.Resolved()
	var out []string
	for _, kv := range []struct {
		flag string
		n    int
	}{{"--keep-last", last}, {"--keep-daily", daily}, {"--keep-weekly", weekly}, {"--keep-monthly", monthly}} {
		if kv.n > 0 {
			out = append(out, kv.flag, strconv.Itoa(kv.n))
		}
	}
	return out
}

// Text is the retention for people: "7 daily, 4 weekly".
func (k VaultKeep) Text() string {
	last, daily, weekly, monthly := k.Resolved()
	var parts []string
	for _, kv := range []struct {
		n    int
		word string
	}{{last, "last"}, {daily, "daily"}, {weekly, "weekly"}, {monthly, "monthly"}} {
		if kv.n > 0 {
			parts = append(parts, fmt.Sprintf("%d %s", kv.n, kv.word))
		}
	}
	return strings.Join(parts, ", ")
}

// MarshalJSON shows resolved values, never a pointer or a null.
func (k VaultKeep) MarshalJSON() ([]byte, error) {
	last, daily, weekly, monthly := k.Resolved()
	return json.Marshal(struct {
		Last    int `json:"last"`
		Daily   int `json:"daily"`
		Weekly  int `json:"weekly"`
		Monthly int `json:"monthly"`
	}{last, daily, weekly, monthly})
}

// MarshalJSON shows resolved values. The two file paths are shown as
// written: they are paths, not secrets.
func (v Vault) MarshalJSON() ([]byte, error) {
	return json.Marshal(struct {
		Enabled       bool          `json:"enabled"`
		Endpoint      string        `json:"endpoint"`
		Region        string        `json:"region"`
		Bucket        string        `json:"bucket"`
		Prefix        string        `json:"prefix"`
		AccessKey     string        `json:"access_key"`
		SecretKeyFile string        `json:"secret_key_file"`
		PasswordFile  string        `json:"password_file"`
		Quota         string        `json:"quota"`
		QuotaBytes    int64         `json:"quota_bytes"`
		WALInterval   time.Duration `json:"wal_interval"`
		Keep          VaultKeep     `json:"keep"`
		MaxAge        time.Duration `json:"max_age"`
	}{v.Enabled, v.Endpoint, v.EffectiveRegion(), v.Bucket, v.EffectivePrefix(), v.AccessKey, v.SecretKeyFile, v.PasswordFile,
		v.Quota, v.QuotaBytes(), v.EffectiveWALInterval(), v.Keep, v.EffectiveMaxAge()})
}

// VaultFor reports whether the off-site copy applies to a server: the vault
// is enabled and the server does not say vault: false.
func (c *Config) VaultFor(s Server) bool {
	return c.Vault.Enabled && (s.Vault == nil || *s.Vault)
}

var sizeRe = regexp.MustCompile(`^([0-9]+(?:\.[0-9]+)?)\s*([a-zA-Z]*)$`)

// ParseSize reads "500GB", "2 TB", "100 GiB" or a number of bytes. GB and TB
// are powers of 1000, as storage is sold; GiB and TiB powers of 1024. Empty
// = 0.
func ParseSize(s string) (int64, error) {
	s = strings.TrimSpace(s)
	if s == "" {
		return 0, nil
	}
	m := sizeRe.FindStringSubmatch(s)
	if m == nil {
		return 0, fmt.Errorf("%q is not a size (use \"500GB\" or \"2TB\")", s)
	}
	n, err := strconv.ParseFloat(m[1], 64)
	if err != nil {
		return 0, fmt.Errorf("%q is not a size (use \"500GB\" or \"2TB\")", s)
	}
	mult := map[string]float64{
		"": 1, "b": 1,
		"kb": 1e3, "mb": 1e6, "gb": 1e9, "tb": 1e12,
		"k": 1e3, "m": 1e6, "g": 1e9, "t": 1e12,
		"kib": 1 << 10, "mib": 1 << 20, "gib": 1 << 30, "tib": 1 << 40,
		"go": 1e9, "to": 1e12, // French units: gigaoctet, téraoctet
	}[strings.ToLower(m[2])]
	if mult == 0 {
		return 0, fmt.Errorf("%q: unknown unit %q (use GB or TB)", s, m[2])
	}
	v := n * mult
	if v > math.MaxInt64/2 {
		return 0, fmt.Errorf("%q is too large", s)
	}
	return int64(math.Round(v)), nil
}

var bucketRe = regexp.MustCompile(`^[a-z0-9][a-z0-9.-]{1,61}[a-z0-9]$`)
var prefixRe = regexp.MustCompile(`^[A-Za-z0-9._-]+(/[A-Za-z0-9._-]+)*$`)

// validateVault returns one sentence per problem of the vault block. A
// disabled block is only checked for what would break once enabled.
func validateVault(c *Config) []string {
	v := c.Vault
	var p []string
	add := func(format string, a ...any) { p = append(p, fmt.Sprintf(format, a...)) }
	if v.Quota != "" {
		if _, err := ParseSize(v.Quota); err != nil {
			add("vault.quota: %v", err)
		}
	}
	if w := v.WALInterval; w != nil && *w != 0 && *w < MinVaultWALInterval {
		add("vault.wal_interval must be at least %s, or 0 to copy only after backups", MinVaultWALInterval)
	}
	if m := v.MaxAge; m != nil && *m <= 0 {
		add("vault.max_age must be positive (for example \"36h\")")
	}
	for _, kv := range []struct {
		n    *int
		name string
	}{{v.Keep.Last, "last"}, {v.Keep.Daily, "daily"}, {v.Keep.Weekly, "weekly"}, {v.Keep.Monthly, "monthly"}} {
		if kv.n != nil && *kv.n < 0 {
			add("vault.keep.%s cannot be negative", kv.name)
		}
	}
	if len(v.Keep.Args()) == 0 {
		add("vault.keep keeps nothing: set at least one of last, daily, weekly or monthly above 0")
	}
	if pr := v.EffectivePrefix(); pr != "" && !prefixRe.MatchString(pr) {
		add("vault.prefix %q may only hold letters, digits, '.', '-', '_' and '/' between folder names", pr)
	}
	for _, f := range []struct{ name, path string }{{"secret_key_file", v.SecretKeyFile}, {"password_file", v.PasswordFile}} {
		if f.path != "" && !filepath.IsAbs(f.path) {
			add("vault.%s must be an absolute path", f.name)
		}
	}
	if !v.Enabled {
		return p
	}
	u, err := url.Parse(strings.TrimSpace(v.Endpoint))
	switch {
	case strings.TrimSpace(v.Endpoint) == "":
		add("vault.endpoint is empty (for OVHcloud: https://s3.<region>.io.cloud.ovh.net)")
	case err != nil || (u.Scheme != "https" && u.Scheme != "http") || u.Host == "":
		add("vault.endpoint %q must be a URL starting with https:// (for OVHcloud: https://s3.<region>.io.cloud.ovh.net)", v.Endpoint)
	case u.Path != "" && u.Path != "/":
		add("vault.endpoint %q must not hold a path: put the bucket in vault.bucket and the folder in vault.prefix", v.Endpoint)
	}
	if !bucketRe.MatchString(v.Bucket) {
		add("vault.bucket %q is not a bucket name (3 to 63 lowercase letters, digits, '.' and '-')", v.Bucket)
	}
	if strings.TrimSpace(v.AccessKey) == "" {
		add("vault.access_key is empty: it is the access key id of the S3 user")
	}
	return p
}
