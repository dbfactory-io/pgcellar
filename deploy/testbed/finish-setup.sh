#!/usr/bin/env bash
# finish-setup.sh: turn the filled .env into the files the stack needs, without
# ever printing a secret. Run it on the Pi from the kit directory:
#
#   cd ~/pgcellar-testbed && ./finish-setup.sh
#
# What it does:
#   1. writes the Barman .pgpass (both roles, ports 5433-5438) into the Barman
#      volume, owned by the container's barman user (uid 997), mode 0600;
#   2. generates an admin password for the web UI if PGCELLAR_ADMIN_PASSWORD is
#      not in .env yet, stores it there, and writes its bcrypt hash into
#      etc/pgcellar/pgcellar.yaml;
#   3. writes TELEGRAM_CHAT_ID into pgcellar.yaml when it is set in .env.
# It can be run again: every step is idempotent.
set -euo pipefail
cd "$(dirname "$0")"

ENV_FILE=.env
YAML=etc/pgcellar/pgcellar.yaml
BARMAN_VOLUME=${BARMAN_VOLUME:-/mnt/usbdata/pgcellar/barman}
BARMAN_UID=${BARMAN_UID:-997}

[ -f "$ENV_FILE" ] || { echo "no $ENV_FILE: copy .env.example first"; exit 1; }
chmod 600 "$ENV_FILE"
# shellcheck disable=SC1090
set -a; . "./$ENV_FILE"; set +a

need() { [ -n "${!1:-}" ] || { echo "$1 is empty in $ENV_FILE"; exit 1; }; }
need BARMAN_PASSWORD
need STREAMING_BARMAN_PASSWORD

# 1. .pgpass: host:port:database:user:password, one line per role and port.
tmp=$(mktemp)
for port in 5433 5434 5435 5436 5437 5438; do
  printf '10.8.0.1:%s:*:barman:%s\n' "$port" "$BARMAN_PASSWORD" >> "$tmp"
  printf '10.8.0.1:%s:*:streaming_barman:%s\n' "$port" "$STREAMING_BARMAN_PASSWORD" >> "$tmp"
done
sudo -n install -d -o "$BARMAN_UID" -g "$BARMAN_UID" -m 750 "$BARMAN_VOLUME"
sudo -n install -o "$BARMAN_UID" -g "$BARMAN_UID" -m 600 "$tmp" "$BARMAN_VOLUME/.pgpass"
rm -f "$tmp"
echo "1. .pgpass written: $BARMAN_VOLUME/.pgpass ($(sudo -n wc -l < "$BARMAN_VOLUME/.pgpass") lines, mode 600, uid $BARMAN_UID)"

# 2. admin password and its bcrypt hash
if [ -z "${PGCELLAR_ADMIN_PASSWORD:-}" ]; then
  PGCELLAR_ADMIN_PASSWORD=$(openssl rand -base64 18 | tr -d '/+=' | cut -c1-20)
  printf '\n# web UI admin password, generated by finish-setup.sh\nPGCELLAR_ADMIN_PASSWORD=%s\n' "$PGCELLAR_ADMIN_PASSWORD" >> "$ENV_FILE"
  echo "2. admin password generated and stored in $ENV_FILE (read it with: grep PGCELLAR_ADMIN_PASSWORD $ENV_FILE)"
else
  echo "2. admin password already in $ENV_FILE"
fi
hash=$(PW="$PGCELLAR_ADMIN_PASSWORD" python3 - <<'PY'
import bcrypt, os
print(bcrypt.hashpw(os.environ["PW"].encode(), bcrypt.gensalt(12)).decode())
PY
)
if grep -q 'password_hash: "CHANGE_ME_BCRYPT_HASH"' "$YAML"; then
  python3 - "$YAML" "$hash" <<'PY'
import sys
path, h = sys.argv[1], sys.argv[2]
s = open(path, encoding="utf-8").read().replace('password_hash: "CHANGE_ME_BCRYPT_HASH"', 'password_hash: "%s"' % h, 1)
open(path, "w", encoding="utf-8").write(s)
PY
  echo "   admin hash written into $YAML"
else
  echo "   $YAML already has an admin hash (not touched)"
fi

# 3. Telegram chat id (not a secret, the token stays in .env)
if [ -n "${TELEGRAM_CHAT_ID:-}" ] && grep -q 'chat_id: "CHANGE_ME"' "$YAML"; then
  sed -i "s/chat_id: \"CHANGE_ME\"/chat_id: \"$TELEGRAM_CHAT_ID\"/" "$YAML"
  echo "3. chat_id written into $YAML"
elif [ -n "${TELEGRAM_CHAT_ID:-}" ]; then
  echo "3. chat_id already set in $YAML"
else
  echo "3. TELEGRAM_CHAT_ID not in $ENV_FILE: alerts stay off until you add it"
fi
[ -n "${TELEGRAM_BOT_TOKEN:-}" ] && echo "   bot token present in $ENV_FILE" || echo "   TELEGRAM_BOT_TOKEN empty in $ENV_FILE"

echo "done. next: ./check-from-pi.sh (needs the roles on hawking first), then: sudo docker compose up -d"
